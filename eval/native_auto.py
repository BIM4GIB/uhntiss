"""Causal Auto research. Train only on isolated, explicitly named recordings.

All mimic grooves remain outside training. Their legacy labels are weak labels:
fixed-grid alignment drifts in several takes. They are a diagnostic, not a claim
of human-annotated accuracy. Python is never loaded by the device.
"""

from __future__ import annotations
import argparse
import hashlib
import json
import subprocess
from pathlib import Path
import numpy as np
import soundfile as sf

ROOT = Path(__file__).resolve().parents[1]
NAMES = ("kick", "snare", "hat")
GAINS = (0.5, 1.0, 2.0)


def analyze(binary, samples, sr, gate=0.010):
    p = subprocess.run(
        [str(binary), str(sr), str(gate)],
        input=np.asarray(samples, dtype="<f4").tobytes(),
        capture_output=True,
        check=True,
    )
    rows = [list(map(float, row.split(","))) for row in p.stdout.decode().splitlines()]
    return np.asarray(rows).reshape(-1, 18)


def read(path):
    y, sr = sf.read(path, dtype="float32")
    return (y.mean(1) if y.ndim > 1 else y), sr


def isolated(binary):
    """Split whole source attacks before gain augmentation; no sibling leakage."""
    train, heldout, provenance = [], [], []
    group_offset = 0
    for path in sorted((ROOT / "calibration").glob("*.wav")):
        label = NAMES.index("hat" if path.stem.startswith("hat") else path.stem)
        y, sr = read(path)
        rows = analyze(binary, y, sr, 0.018)
        # Isolated calibration, not groove processing: omit incomplete edge
        # attacks and secondary bursts within 250ms of a stronger attack.
        primary = []
        for row in sorted(rows, key=lambda r: -r[2]):
            if 0.025 < row[0] < len(y) / sr - 0.2 and all(
                abs(row[0] - r[0]) > 0.25 for r in primary
            ):
                primary.append(row)
        primary.sort(key=lambda r: r[0])
        test = [r for i, r in enumerate(primary) if i % 4 == 3]
        learning = [r for i, r in enumerate(primary) if i % 4 != 3]
        heldout.extend(
            dict(source=str(path.relative_to(ROOT)), time=float(r[0]), drum=label)
            for r in test
        )
        for gain in GAINS:
            for row in analyze(binary, y * gain, sr):
                group = int(np.argmin(np.abs(rows[:, 0] - row[0])))
                if (
                    0.025 < row[0] < len(y) / sr - 0.02
                    and abs(rows[group, 0] - row[0]) < 0.025
                    and not any(abs(row[0] - r[0]) < 0.2 for r in test)
                ):
                    train.append((row[4:], label, group_offset + group))
        group_offset += len(rows)
        provenance.append(
            dict(
                source=str(path.relative_to(ROOT)),
                sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                primary_training_attacks=len(learning),
                heldout_attacks=len(test),
            )
        )
    return train, heldout, provenance


def train(binary):
    rows, heldout, provenance = isolated(binary)
    x = np.array([r[0] for r in rows])
    # Late attack shape receives four times the squared-distance weight;
    # selected by source-attack-group CV on training attacks, not reserved hits.
    scale = np.maximum(x.std(0), 0.2) / np.sqrt([1] * 6 + [4] * 6 + [1, 1])

    def vector(a):
        return "{" + ", ".join(format(float(v), ".10g") for v in a) + "}"

    header = "// Generated by python -m eval.native_auto train. Do not edit.\n// 10ms causal features; isolated recordings only; held-out attacks excluded.\n#pragma once\n#include <array>\nnamespace pocket::model {\n"
    header += "inline constexpr std::array<double, 14> scale = " + vector(scale) + ";\n"
    header += "inline constexpr double windowSeconds = .010;\n"
    header += (
        "struct Example { std::array<double,14> features; int drum; int source; };\n"
    )
    header += f"inline constexpr std::array<Example,{len(rows)}> examples = {{{{\n"
    header += (
        ",\n".join(
            "  {" + vector(f) + ", " + str(d) + ", " + str(g) + "}" for f, d, g in rows
        )
        + "\n}};\n}\n"
    )
    (ROOT / "native/pocket/include/pocket/attack_model.hpp").write_text(header)
    info = dict(
        compiled_model_sha256=hashlib.sha256(header.encode()).hexdigest(),
        feature_version=1,
        window_ms=10,
        distance_weights=[1] * 6 + [4] * 6 + [1, 1],
        gain_augmentation=GAINS,
        prototypes=len(rows),
        training=provenance,
        heldout_attacks=heldout,
        exclusions="Every fourth primary attack per source is excluded before all gain augmentation. No mimic or fixture groove is used for training.",
    )
    (ROOT / "native/pocket/auto-model.json").write_text(
        json.dumps(info, indent=2) + "\n"
    )
    print(
        f"Wrote {len(rows)} attack prototypes; reserved {len(heldout)} source attacks."
    )


def match(pred, refs, tolerance=0.075):
    pairs = []
    used = set()
    other = set()
    candidates = sorted(
        (abs(t - r["t"]), i, j)
        for i, t in enumerate(pred)
        for j, r in enumerate(refs)
        if abs(t - r["t"]) < tolerance
    )
    for _, i, j in candidates:
        if i not in used and j not in other:
            pairs.append((i, j))
            used.add(i)
            other.add(j)
    return pairs


def report(binary):
    from eval.featurelab import labeled_onsets

    refs = labeled_onsets()
    clips = []
    for path in sorted((ROOT / "mimic").glob("*.mimic.wav")):
        y, sr = read(path)
        rows = analyze(binary, y, sr)
        take = path.name.replace(".mimic.wav", "")
        r = [v for v in refs if v["take"] == take]
        pairs = match(rows[:, 0], r)
        clips.append(
            dict(
                take=take,
                detected=len(rows),
                matched=len(pairs),
                unmatched_detections=len(rows) - len(pairs),
                unmatched_weak_labels=len(r) - len(pairs),
                matched_class_accuracy=sum(
                    int(rows[i, 1]) == NAMES.index(r[j]["label"]) for i, j in pairs
                )
                / max(1, len(pairs)),
            )
        )
    return dict(
        reference="Legacy auto-aligned labels; several grids drift. No groove was used for training. Unmatched detections may include unlabelled real hits.",
        clips=clips,
    )


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("command", choices=("train", "report"))
    p.add_argument(
        "--binary", type=Path, default=ROOT / "native/pocket/build/pocket_analyze"
    )
    args = p.parse_args()
    if args.command == "train":
        train(args.binary.resolve())
    else:
        print(json.dumps(report(args.binary.resolve()), indent=2))


if __name__ == "__main__":
    main()
