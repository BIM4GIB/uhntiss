"""Generate plugins/pocket/<device>/PocketParams.h from the M4L builders in m4l/<device>/build_device.py,
so the plug-ins expose exactly the panel's controls (labels, ranges, menus) and Sound presets.
    python3 plugins/pocket/gen_params.py            # writes all three headers
"""
import importlib.util, pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
UNIT = {5: "%", 7: "st"}
# gen~ param name -> C struct field where the C mirror uses another name
ALIASES = {"pocket303": {"glide": "slide", "square": "wave"}}


def load(dev):
    spec = importlib.util.spec_from_file_location(f"{dev}_build", ROOT / "m4l" / dev / "build_device.py")
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m); return m


def controls_303(m):
    ctrls = [dict(kind="slider", gen=g, label=l, min=mn, max=mx, init=init, unit=UNIT.get(u, ""))
             for g, l, mn, mx, init, u, conv in m.PARAMS]
    ctrls.append(dict(kind="menu", gen="square", label="Wave", items=["Saw", "Square"], init=0))
    presets = [(name, list(vals) + [0]) for name, vals in m.PRESETS]
    return ctrls, presets


def controls_sections(m):
    prefix = getattr(m, "PREFIX_LABELS", set())
    ctrls = []
    for sname, cs in m.SECTIONS:
        for c in cs:
            if c[0] == "slider":
                _, g, l, mn, mx, init, u, conv = c
                ctrls.append(dict(kind="slider", gen=g, label=f"{sname} {l}" if l in prefix else l, min=mn, max=mx, init=init, unit=UNIT.get(u, "")))
            else:
                _, g, l, items, init = c
                ctrls.append(dict(kind="menu", gen=g, label=f"{sname} {l}" if l in prefix else l, items=list(items), init=init))
    presets = [(name, [vals.get(c["gen"], c["init"]) for c in ctrls]) for name, vals in m.PRESETS]
    return ctrls, presets


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit(dev, ctrls, presets):
    al = ALIASES.get(dev, {})
    out = ["#pragma once", f"// Generated by plugins/pocket/gen_params.py from m4l/{dev}/build_device.py. Do not edit.",
           f"#define POCKET_PARAM_COUNT {len(ctrls)}", f"#define POCKET_PRESET_COUNT {len(presets)}",
           "typedef struct { const char *symbol, *name, *unit; float min, max, def; int is_int; const char *const *enums; int enum_count; } PocketParamMeta;"]
    for c in ctrls:
        if c["kind"] == "menu":
            out.append(f"static const char *const pocket_enum_{c['gen']}[] = {{{', '.join(cstr(i) for i in c['items'])}}};")
    out.append(f"static const PocketParamMeta POCKET_PARAMS[POCKET_PARAM_COUNT] = {{")
    for c in ctrls:
        if c["kind"] == "slider":
            out.append(f"    {{{cstr(c['gen'])}, {cstr(c['label'])}, {cstr(c['unit'])}, {c['min']}, {c['max']}, {c['init']}, 0, 0, 0}},")
        else:
            out.append(f"    {{{cstr(c['gen'])}, {cstr(c['label'])}, \"\", 0, {len(c['items']) - 1}, {c['init']}, 1, pocket_enum_{c['gen']}, {len(c['items'])}}},")
    out.append("};")
    out.append("static inline double *pocket_param_ptr(Params *p, int i) {")
    out.append("    switch (i) {")
    for i, c in enumerate(ctrls):
        out.append(f"    case {i}: return &p->{al.get(c['gen'], c['gen'])};")
    out.append("    default: return 0;\n    }\n}")
    out.append("static inline double pocket_ctrl_to_gen(int i, double v) {\n    const PocketParamMeta *m = &POCKET_PARAMS[i];\n    return m->is_int ? v : (v - m->min) / (m->max - m->min);\n}")
    out.append(f"static const char *const POCKET_PRESET_NAMES[POCKET_PRESET_COUNT] = {{{', '.join(cstr(n) for n, _ in presets)}}};")
    out.append("static const float POCKET_PRESETS[POCKET_PRESET_COUNT][POCKET_PARAM_COUNT] = {")
    for name, vals in presets:
        out.append("    {" + ", ".join(str(v) for v in vals) + "},")
    out.append("};")
    (HERE / dev / "PocketParams.h").write_text("\n".join(out) + "\n")
    print(f"ok   {dev}: {len(ctrls)} params, {len(presets)} presets")


if __name__ == "__main__":
    emit("pocket303", *controls_303(load("pocket303")))
    emit("pocket101", *controls_sections(load("pocket101")))
    emit("pocketkick", *controls_sections(load("pocketkick")))
